async function seedDB() {
  try {
    const mongoUri = process.env.MONGODB_URI || 'mongodb://localhost:27017/v1st-nutrition';
    console.log('Connecting to MongoDB for seeding:', mongoUri);
    await mongoose.connect(mongoUri);

    console.log('Connected! Purging old product records...');
    await Product.deleteMany({});

    console.log(`Inserting ${sampleProducts.length} authentic supplement products...`);
    await Product.insertMany(sampleProducts);

    console.log('Database seeded successfully with authentic Surat sports nutrition products!');
    process.exit(0);
  } catch (error) {
    console.error('Seeding error:', error.message);
    process.exit(1);
  }
}

if (require.main === module) {
  seedDB();
}

module.exports = { sampleProducts, seedDB };
